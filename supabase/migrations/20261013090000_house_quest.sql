-- House Quest: a self-contained two-player (David & Anne) house-upgrade planning
-- game that piggybacks on this Supabase project, exactly like the Almanac weight
-- tracker. All tables are prefixed hq_ so the whole feature can be lifted out
-- later. RLS is permissive for the anon role (same posture as the rest of this
-- project); the Netlify function is the trust boundary and enforces per-user
-- scoping via an HMAC session token. Content/logic tables that never change at
-- runtime (achievements, holidays, wildcard deck, drop reasons) live as server
-- constants in _lib/housequest.js, not here. Only the card catalog is a table,
-- so custom treats can persist.

-- ---------------------------------------------------------------- household
-- Singleton row (one household). Balance is never stored; it is the sum of the
-- ledger. These are the tunable settings plus shared counters.
create table if not exists public.hq_household (
  id              int primary key default 1,
  weekly_budget   numeric not null default 375,
  deposit_day     text    not null default 'Monday',   -- Sunday..Saturday
  rollover        boolean not null default true,
  drops_per_month int     not null default 2,
  holidays_on     boolean not null default true,
  wildcard_on     boolean not null default true,
  season_boost_on boolean not null default true,
  treats_on       boolean not null default true,
  max_hand        int     not null default 5,          -- 3 / 5 / 7
  xp              int     not null default 0,
  season          text    not null default 'Fall',     -- Spring/Summer/Fall/Winter
  rooms           jsonb   not null default '[]'::jsonb, -- floor-plan room defs
  cats            jsonb   not null default '["Kitchen","Bath","Bedroom","Living","Yard","Garage","Exterior","Systems","Decor"]'::jsonb,
  draft_first_next text   not null default 'David',     -- who picks first next draft
  yes_streak      jsonb   not null default '{"David":0,"Anne":0}'::jsonb,
  current_drop    jsonb,                                -- unclaimed drop, or null
  claimed_holidays jsonb  not null default '{}'::jsonb, -- { holidayId: true }
  wildcard_week   text,                                 -- ISO week this roll belongs to
  wildcard_result jsonb,                                -- { title, body, delta } or null
  last_deposit_week text,                               -- guard so the job runs once/week
  single_row      boolean not null default true,
  created_at      timestamptz not null default now()
);
create unique index if not exists hq_household_singleton on public.hq_household (single_row);

-- ---------------------------------------------------------------- users
-- Exactly two: David and Anne. No open registration. Passcode is claimed on
-- first login (pw_hash starts null). notif_prefs is the 9 category booleans.
create table if not exists public.hq_users (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,                 -- 'David' | 'Anne' (display + logic key)
  username    text not null unique,          -- 'david' | 'anne' (lowercased login)
  pw_hash     text,                          -- scrypt hex, null until claimed
  pw_salt     text,
  notif_prefs jsonb not null default '{"plan":true,"pitch":true,"vote":true,"card":true,"comment":true,"finish":true,"money":true,"recap":true,"nudge":true}'::jsonb,
  quiet_hours boolean not null default true, -- hold pushes 10pm–7am
  ui          jsonb not null default '{}'::jsonb, -- per-user UI cursors (e.g. dismissed board notice)
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------- upgrades
create table if not exists public.hq_upgrades (
  id            bigint generated by default as identity primary key,
  title         text not null,
  cat           text not null default 'Decor',
  cost          numeric not null default 0,
  fund          text not null default 'lump',      -- 'lump' | 'gradual'
  pieces        int not null default 1,
  pieces_done   int not null default 0,
  unit          text default 'pieces',
  saved         numeric not null default 0,        -- savings jar
  spent_so_far  numeric not null default 0,
  actual        numeric,                           -- final actual cost when done
  effort        int not null default 1,            -- 1 Quick / 2 Weekend / 3 Big
  who           text not null default 'Both',      -- David | Anne | Both | Hire out
  season        text not null default 'Any',       -- Any/Spring/Summer/Fall/Winter
  link          text,
  note          text,
  before_photo_url text,
  after_photo_url  text,
  by            text not null,                     -- pitched_by: David | Anne
  status        text not null default 'pending',   -- pending/approved/shelved/done
  passed_by     text,
  planned       boolean not null default false,    -- "In the plan" after a draft lock
  done_month    text,                              -- e.g. 'Oct'
  done_season   text,
  peek          jsonb not null default '{}'::jsonb,-- { David:true } who peeked the vote
  created_at    timestamptz not null default now()
);
create index if not exists hq_upgrades_status_idx on public.hq_upgrades (status);

-- one importance rating per user per upgrade (the "imp" map is assembled from these)
create table if not exists public.hq_votes (
  id          bigint generated by default as identity primary key,
  upgrade_id  bigint not null references public.hq_upgrades(id) on delete cascade,
  user_name   text not null,                     -- 'David' | 'Anne'
  rating      int not null,                      -- 1..10
  created_at  timestamptz not null default now(),
  unique (upgrade_id, user_name)
);

-- cards played on an upgrade (champion/double/fast/second/override/block…)
create table if not exists public.hq_card_plays (
  id          bigint generated by default as identity primary key,
  upgrade_id  bigint not null references public.hq_upgrades(id) on delete cascade,
  who         text not null,
  card_type   text not null,
  blocked     boolean not null default false,
  created_at  timestamptz not null default now()
);

create table if not exists public.hq_comments (
  id          bigint generated by default as identity primary key,
  upgrade_id  bigint not null references public.hq_upgrades(id) on delete cascade,
  who         text not null,
  text        text not null,
  created_at  timestamptz not null default now()
);

create table if not exists public.hq_history (
  id          bigint generated by default as identity primary key,
  upgrade_id  bigint not null references public.hq_upgrades(id) on delete cascade,
  text        text not null,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------- cards / effects / ledger
-- A player's hand = their cards with used_at null.
create table if not exists public.hq_cards (
  id          bigint generated by default as identity primary key,
  owner       text not null,                     -- 'David' | 'Anne'
  card_type   text not null,
  drawn_at    timestamptz not null default now(),
  used_at     timestamptz
);
create index if not exists hq_cards_hand_idx on public.hq_cards (owner) where used_at is null;

-- Armed refund effects (coupon / golden hammer) awaiting the next finish.
create table if not exists public.hq_effects (
  id          bigint generated by default as identity primary key,
  who         text not null,
  card_type   text not null,                     -- 'coupon' | 'halfoff'
  created_at  timestamptz not null default now(),
  used_at     timestamptz
);

create table if not exists public.hq_ledger (
  id          bigint generated by default as identity primary key,
  label       text not null,
  amount      numeric not null,                  -- +/- dollars
  kind        text not null,                     -- deposit/spend/bonus/adjust
  upgrade_id  bigint references public.hq_upgrades(id) on delete set null,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------- draft
create table if not exists public.hq_drafts (
  id           bigint generated by default as identity primary key,
  week_start   text not null,
  pool         numeric,
  first_picker text not null default 'David',
  status       text not null default 'open',      -- open / finished / locked
  passed       jsonb not null default '{"David":false,"Anne":false}'::jsonb,
  locked       jsonb not null default '{"David":false,"Anne":false}'::jsonb,
  created_at   timestamptz not null default now()
);

create table if not exists public.hq_draft_picks (
  id          bigint generated by default as identity primary key,
  draft_id    bigint not null references public.hq_drafts(id) on delete cascade,
  upgrade_id  bigint not null references public.hq_upgrades(id) on delete cascade,
  who         text not null,
  amount      numeric not null,
  pick_no     int not null,
  created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------- notifications
create table if not exists public.hq_notifications (
  id          bigint generated by default as identity primary key,
  to_user     text not null,                     -- 'David' | 'Anne'
  category    text not null,                     -- plan/pitch/vote/card/comment/finish/money/recap/nudge
  text        text not null,
  upgrade_id  bigint references public.hq_upgrades(id) on delete set null,
  tab         text,                              -- optional deep-link tab
  read        boolean not null default false,
  pushed      boolean not null default false,    -- has the push sender handled it
  created_at  timestamptz not null default now()
);
create index if not exists hq_notifs_to_idx on public.hq_notifications (to_user, created_at desc);

-- ---------------------------------------------------------------- card catalog
-- Seeded with the 12 power cards + 11 treats. Custom treats are inserted here
-- (custom=true, owner set to the creator so both still draw them).
create table if not exists public.hq_card_catalog (
  type    text primary key,
  name    text not null,
  rarity  text not null,                         -- Common | Rare | Legendary
  glyph   text not null,
  target  text not null,                         -- board/shelf/block/peek/override/instant/armed/treat
  amount  numeric,
  pct     numeric,
  cap     numeric,
  value   numeric,
  descr   text,
  custom  boolean not null default false,
  owner   text
);

-- ---------------------------------------------------------------- events log
-- Drops log + achievement earned-dates (type tells them apart).
create table if not exists public.hq_events (
  id          bigint generated by default as identity primary key,
  type        text not null,                     -- drop | holiday | wildcard | achievement
  payload     jsonb not null default '{}'::jsonb,
  created_at  timestamptz not null default now()
);
create index if not exists hq_events_type_idx on public.hq_events (type, created_at desc);

-- ---------------------------------------------------------------- push subscriptions
create table if not exists public.hq_push_subs (
  id         bigint generated by default as identity primary key,
  user_id    uuid references public.hq_users(id) on delete cascade,
  endpoint   text not null unique,
  p256dh     text not null,
  auth       text not null,
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------- RLS (permissive anon)
do $$
declare t text;
begin
  foreach t in array array[
    'hq_household','hq_users','hq_upgrades','hq_votes','hq_card_plays','hq_comments',
    'hq_history','hq_cards','hq_effects','hq_ledger','hq_drafts','hq_draft_picks',
    'hq_notifications','hq_card_catalog','hq_events','hq_push_subs'
  ] loop
    execute format('alter table public.%I enable row level security;', t);
    execute format('drop policy if exists "hq anon all" on public.%I;', t);
    execute format('create policy "hq anon all" on public.%I for all to anon using (true) with check (true);', t);
  end loop;
end $$;

